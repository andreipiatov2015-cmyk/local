#!/bin/sh
# Распаковывает собранный релиз nginx+RTMP (ASSET, $1) поверх каталога
# установки (DEST_DIR, $2), сохраняя руками правленный conf/nginx.conf,
# если он там уже есть.
#
# Регрессия, которая реально уронила сайт при обновлении до 1.0.25:
# tar -xzf затирал conf/nginx.conf боевым дефолтным файлом из чистой
# сборки, если на момент установки nginx оказывался не запущен (процесс
# мог упасть по не связанной с пакетом причине ДО обновления) — защита
# "не трогаем файлы, если nginx уже запущен" в postinst от этого не
# спасала, потому что смотрела на текущее состояние процесса, а не на
# то, настроен ли вообще конфиг на диске. Наличие файла — правильный
# признак "это уже чей-то рабочий конфиг, не трогать", а не то, бежит ли
# прямо сейчас процесс, который его читает.
#
# Вынесено в отдельный файл ради тестируемости (см.
# tests/test_extract_nginx_release.py), по тому же принципу, что и
# check_nginx_running.sh.
set -e

ASSET="$1"
DEST_DIR="$2"

BACKUP=""
if [ -f "$DEST_DIR/conf/nginx.conf" ]; then
    BACKUP=$(mktemp)
    cp "$DEST_DIR/conf/nginx.conf" "$BACKUP"
fi

mkdir -p "$DEST_DIR"
tar -xzf "$ASSET" -C "$DEST_DIR"

if [ -n "$BACKUP" ]; then
    cp "$BACKUP" "$DEST_DIR/conf/nginx.conf"
    rm -f "$BACKUP"
    echo "Прежний $DEST_DIR/conf/nginx.conf сохранён (не перезаписан дефолтным)."
fi
